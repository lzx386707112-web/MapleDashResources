function 五转下一步() {
    if (cm.isQuestCompleted(1465)) return null;
    if (!cm.isQuestCompleted(1460)) return "去 270010111 找旁观者接 #b1460 " + 五转任务[0][1] + "#k";
    if (!cm.isQuestCompleted(1481)) {
        return "去 270000000 找神殿管理人接 #b1481 " + 五转任务[1][1] +
            "#k（要总星力 100 / 武器 10 星）";
    }
    if (!cm.isQuestCompleted(1461)) {
        if (cm.isQuestStarted(1461) || 已碰过女神石()) {
            var 缺 = [];
            for (var i = 0; i < 女神石任务.length; i++) {
                if (!cm.isQuestCompleted(女神石任务[i][0])) {
                    缺.push("#b" + 女神石任务[i][0] + "#k " + 女神石任务[i][1]);
                }
            }
            if (缺.length > 0) {
                return "还差女神石：" + 缺.join("、") + "（还剩 " + 缺.length + " 块）";
            }
            return "三块石头齐了，回 270010111 找旁观者交 #b1461#k";
        }
        return "回 270010111 找旁观者接 #b1461 " + 五转任务[2][1] + "#k";
    }
    return "回 270010111 找旁观者接并交 #b1465 " + 五转任务[3][1] + "#k";
}

function 已碰过女神石() {
    for (var i = 0; i < 女神石任务.length; i++) {
        var id = 女神石任务[i][0];
        if (cm.isQuestStarted(id) || cm.isQuestCompleted(id)) return true;
    }
    return false;
}

